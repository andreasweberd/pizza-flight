-- Drop all existing tables/objects (including any added in Task 08)
DROP ALL OBJECTS;

-- -----------------------------------------------------------------------------
-- 1. Vending Machines
-- -----------------------------------------------------------------------------
CREATE TABLE machines (
    machine_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(20)  NOT NULL UNIQUE,
    city           VARCHAR(50)  NOT NULL,
    location_name  VARCHAR(100) NOT NULL,
    status         VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'OFFLINE')),
    installed_date DATE         NOT NULL
);

-- -----------------------------------------------------------------------------
-- 2. Pizzas
-- -----------------------------------------------------------------------------
CREATE TABLE pizzas (
    pizza_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60)  NOT NULL UNIQUE,
    category      VARCHAR(30)  NOT NULL CHECK (category IN ('Classic', 'Meat', 'Vegetarian', 'Special')),
    base_price    DECIMAL(6,2) NOT NULL CHECK (base_price > 0),
    bake_time_sec INT          NOT NULL CHECK (bake_time_sec > 0),
    is_vegetarian BOOLEAN      NOT NULL,
    calories      INT          NOT NULL CHECK (calories > 0)
);

-- -----------------------------------------------------------------------------
-- 3. Toppings
-- -----------------------------------------------------------------------------
CREATE TABLE toppings (
    topping_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL UNIQUE,
    extra_price DECIMAL(5,2) NOT NULL CHECK (extra_price >= 0),
    is_vegan    BOOLEAN      NOT NULL
);

-- -----------------------------------------------------------------------------
-- 4. Pizza <-> Toppings (default toppings on each pizza)
-- -----------------------------------------------------------------------------
CREATE TABLE pizza_toppings (
    pizza_id   INT NOT NULL,
    topping_id INT NOT NULL,
    PRIMARY KEY (pizza_id, topping_id),
    FOREIGN KEY (pizza_id)   REFERENCES pizzas(pizza_id),
    FOREIGN KEY (topping_id) REFERENCES toppings(topping_id)
);

-- -----------------------------------------------------------------------------
-- 5. Machine Inventory (stock of each pizza per vending machine)
-- -----------------------------------------------------------------------------
CREATE TABLE machine_inventory (
    machine_id     INT  NOT NULL,
    pizza_id       INT  NOT NULL,
    quantity       INT  NOT NULL CHECK (quantity >= 0),
    last_restocked DATE NOT NULL,
    PRIMARY KEY (machine_id, pizza_id),
    FOREIGN KEY (machine_id) REFERENCES machines(machine_id),
    FOREIGN KEY (pizza_id)   REFERENCES pizzas(pizza_id)
);

-- -----------------------------------------------------------------------------
-- 6. Registered Customers (Loyalty App Users)
-- -----------------------------------------------------------------------------
CREATE TABLE customers (
    customer_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(50)  NOT NULL,
    last_name       VARCHAR(50)  NOT NULL,
    email           VARCHAR(100) NOT NULL UNIQUE,
    city            VARCHAR(50)  NOT NULL,
    loyalty_points  INT          NOT NULL DEFAULT 0 CHECK (loyalty_points >= 0),
    registered_date DATE         NOT NULL
);

-- -----------------------------------------------------------------------------
-- 7. Orders (customer_id is NULL for anonymous walk-up guest orders)
-- -----------------------------------------------------------------------------
CREATE TABLE orders (
    order_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id      INT          NOT NULL,
    customer_id     INT,
    order_timestamp TIMESTAMP    NOT NULL,
    payment_method  VARCHAR(20)  NOT NULL CHECK (payment_method IN ('CARD', 'APP', 'CASH')),
    total_price     DECIMAL(7,2) NOT NULL CHECK (total_price >= 0),
    order_status    VARCHAR(20)  NOT NULL CHECK (order_status IN ('COMPLETED', 'CANCELLED')),
    FOREIGN KEY (machine_id)  REFERENCES machines(machine_id),
    FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

-- -----------------------------------------------------------------------------
-- 8. Order Items (pizzas included in each order)
-- -----------------------------------------------------------------------------
CREATE TABLE order_items (
    order_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INT          NOT NULL,
    pizza_id      INT          NOT NULL,
    quantity      INT          NOT NULL CHECK (quantity > 0),
    unit_price    DECIMAL(6,2) NOT NULL CHECK (unit_price > 0),
    FOREIGN KEY (order_id) REFERENCES orders(order_id),
    FOREIGN KEY (pizza_id) REFERENCES pizzas(pizza_id)
);

